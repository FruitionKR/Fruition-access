-- 이메일 변경 알림 outbox. 이메일 변경 트랜잭션에서 넣으므로 변경과 함께 커밋되고, 롤백되면 같이 사라진다.
-- EmailChangeNotificationJob이 행을 집어 기존 이메일로 발송하고, 성공하면 행을 지운다.
-- 실패하면 backoff로 다시 시도하고, 최대 시도를 넘기면 status를 'failed'로 두어 운영자가 확인한다.
-- 새 이메일은 메일 본문에 가린 값만 실리므로 가린 값(masked_new_email)만 저장한다.
-- 수신자(recipient_email)는 발송에 꼭 필요한 기존 이메일이다.
-- 이메일을 바꾼 뒤 탈퇴해도 알림은 가야 하므로 users FK를 두지 않는다.
CREATE TABLE email_change_notifications (
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id          varchar(255)             NOT NULL,
    recipient_email  varchar(255)             NOT NULL,
    masked_new_email varchar(255)             NOT NULL,
    changed_at       timestamp with time zone NOT NULL,
    status           varchar(16)              NOT NULL DEFAULT 'pending',
    attempts         integer                  NOT NULL DEFAULT 0,
    next_attempt_at  timestamp with time zone NOT NULL DEFAULT now(),
    last_error       varchar(1000),
    created_at       timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT email_change_notifications_pkey PRIMARY KEY (id),
    CONSTRAINT email_change_notifications_status_check CHECK (status IN ('pending', 'failed'))
);

CREATE INDEX idx_email_change_notifications_due
    ON email_change_notifications (next_attempt_at) WHERE status = 'pending';
